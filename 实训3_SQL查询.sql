-- --------------------------------------------
-- 1. 检索全部商品数据
-- --------------------------------------------
SELECT * FROM stocks;

-- --------------------------------------------
-- 2. 检索员工的总收入（工资收入+奖金收入）
-- --------------------------------------------
SELECT 员工编号, 员工姓名, 工资收入, 奖金收入,
       (工资收入 + 奖金收入) AS 总收入
FROM employees;

-- --------------------------------------------
-- 3. 检索奖金收入大于1000的员工数量
-- --------------------------------------------
SELECT COUNT(*) AS 奖金大于1000的员工数量
FROM employees
WHERE 奖金收入 > 1000;

-- --------------------------------------------
-- 4. 检索2018年入职的员工姓名、入职日期、工资收入
-- --------------------------------------------
SELECT 员工姓名, 入职日期, 工资收入
FROM employees
WHERE YEAR(入职日期) = 2018;

-- --------------------------------------------
-- 5. 检索奖金收入为550、1100、1800的员工姓名、奖金收入
-- --------------------------------------------
SELECT 员工姓名, 奖金收入
FROM employees
WHERE 奖金收入 IN (550, 1100, 1800);

-- --------------------------------------------
-- 6. 检索家庭住址在詹天路的员工姓名、家庭住址、联系电话
-- --------------------------------------------
SELECT 员工姓名, 家庭住址, 联系电话
FROM employees
WHERE 家庭住址 LIKE '%詹天路%';

-- --------------------------------------------
-- 7. 检索员工姓名为三个字，其中第二个字为'明'的员工全部信息
-- --------------------------------------------
SELECT *
FROM employees
WHERE 员工姓名 LIKE '_明_';

-- --------------------------------------------
-- 8. 按性别分组，统计各组总人数、平均工资、最高工资、最低工资
-- --------------------------------------------
SELECT 员工性别,
       COUNT(*)              AS 总人数,
       AVG(工资收入)         AS 平均工资收入,
       MAX(工资收入)         AS 最高工资收入,
       MIN(工资收入)         AS 最低工资收入
FROM employees
GROUP BY 员工性别;

-- --------------------------------------------
-- 9. 按销售日期分组，统计每天销售商品总数
-- --------------------------------------------
SELECT 销售日期,
       SUM(销售数量) AS 每天销售商品总数
FROM sales
GROUP BY 销售日期;

-- --------------------------------------------
-- 10. 先按销售日期分组，再按员工编号分组，统计每天各员工销售数量，并给出汇总行
-- --------------------------------------------
SELECT 销售日期,
       员工编号,
       SUM(销售数量) AS 销售数量
FROM sales
GROUP BY 销售日期, 员工编号 WITH ROLLUP;
